// Eduwit One access preflight (spec §14, phase 0). Re-runnable at any time.
// Exercises every row of the prerequisites access list with a real read, list or ping and prints each as
// verified / refused / not_provided / unfilled with what it ran. Never prints or stores a secret.
//
//   node scripts/preflight.ts [--merge docs/preflight-connector.json] [--setup supabase/seed/setup.json] [--md docs/PREFLIGHT-table.md]
//
// In the cloud build environment, outbound HTTPS needs NODE_USE_ENV_PROXY=1. The merge file holds rows the
// build session exercised through its connectors (Supabase, n8n, GitHub); a merged row replaces a script row
// only when the script could not verify that item itself.
import { readFileSync, writeFileSync } from "node:fs";
import { loadJson, type Defaults, type Row, type Status } from "./preflight/lib.ts";
import { probeChatwoot, probeGithub, probeLightsail, probeN8n, probeVercel } from "./preflight/probes-vendors.ts";
import { probeAiKey, probeB2bApi, probeHealth, probeIdentities, probeResend, probeUptimeRobot, probeWhatsApp } from "./preflight/probes-apps.ts";
import { probeDatabase } from "./preflight/probes-db.ts";

type SetupItem = { id: string; title: string; who: string; stores: string; unblocks: string[] };
type Sourced = Row & { source: "script" | "connector" | "none" };

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : undefined;
}

async function runScriptProbes(cfg: Defaults): Promise<Row[]> {
  const single = await Promise.all([
    probeGithub(cfg),
    probeVercel(cfg),
    probeChatwoot(cfg),
    probeN8n(cfg),
    probeLightsail(cfg),
    probeUptimeRobot(cfg),
    probeResend(cfg),
    probeB2bApi(cfg),
    probeWhatsApp(cfg),
    probeAiKey(cfg),
    probeHealth(cfg, "website", "website_health"),
    probeHealth(cfg, "influencer", "influencer_portal"),
  ]);
  return [...single, ...(await probeIdentities(cfg)), ...probeDatabase()];
}

function merge(items: SetupItem[], script: Row[], connector: Row[]): Sourced[] {
  return items.map((item) => {
    const own = script.find((r) => r.id === item.id);
    const viaConnector = connector.find((r) => r.id === item.id);
    if (own?.status === "verified") return { ...own, source: "script" };
    if (viaConnector) return { ...viaConnector, source: "connector" };
    if (own) return { ...own, source: "script" };
    return { id: item.id, status: "unfilled" as Status, ran: "—", detail: "no probe and no connector result", source: "none" };
  });
}

function markdown(items: SetupItem[], rows: Sourced[]): string {
  const cell = (s: string | undefined): string => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  const lines = ["| Item | Status | What was run | Result | Fix | Unblocks |", "| --- | --- | --- | --- | --- | --- |"];
  for (const row of rows) {
    const item = items.find((i) => i.id === row.id);
    lines.push(`| ${cell(item?.title ?? row.id)} | ${row.status} | ${cell(row.ran)}${row.source === "connector" ? " (connector)" : ""} | ${cell(row.detail)} | ${cell(row.fix)} | ${cell(item?.unblocks.join(", "))} |`);
  }
  return lines.join("\n");
}

function setupSeed(rows: Sourced[], at: string): unknown {
  const items: Record<string, unknown> = {};
  for (const row of rows) {
    items[row.id] = {
      status: row.status,
      validated: row.status === "verified",
      validated_at: row.status === "verified" ? at : null,
      ran: row.ran,
      detail: row.detail,
      fix: row.fix ?? null,
      source: row.source,
    };
  }
  return { generated_at: at, generated_by: "scripts/preflight.ts", items };
}

async function main(): Promise<void> {
  const cfg = loadJson<Defaults>("config/defaults.json");
  const { items } = loadJson<{ items: SetupItem[] }>("config/setup-items.json");
  const mergePath = arg("--merge");
  const connector = mergePath ? (JSON.parse(readFileSync(mergePath, "utf8")) as { rows: Row[] }).rows : [];
  const rows = merge(items, await runScriptProbes(cfg), connector);
  const at = new Date().toISOString();
  const table = markdown(items, rows);
  const counts = rows.reduce<Record<string, number>>((acc, r) => ({ ...acc, [r.status]: (acc[r.status] ?? 0) + 1 }), {});
  console.log(`Eduwit One preflight ${at}\n\n${table}\n\n${JSON.stringify(counts)}`);
  const setupPath = arg("--setup");
  if (setupPath) writeFileSync(setupPath, `${JSON.stringify(setupSeed(rows, at), null, 2)}\n`);
  const mdPath = arg("--md");
  if (mdPath) writeFileSync(mdPath, `<!-- generated by scripts/preflight.ts at ${at}; do not edit -->\n\n${table}\n`);
}

await main();
