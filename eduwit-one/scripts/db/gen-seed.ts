// Generates supabase/migrations/0007_seed_settings.sql from config/defaults.json, config/settings.json and the
// preflight's supabase/seed/setup.json, so settings have one source (D-015).
//   node scripts/db/gen-seed.ts           write the migration
//   node scripts/db/gen-seed.ts --check   exit 1 if the committed migration is stale (CI)
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const read = (path: string): unknown => JSON.parse(readFileSync(new URL(path, root), "utf8")) as unknown;
const target = new URL("supabase/migrations/0007_seed_settings.sql", root);

type Json = Record<string, unknown>;

function settings(): Array<[string, unknown]> {
  const defaults = read("config/defaults.json") as Json;
  const fixed = read("config/settings.json") as Json;
  const setup = read("supabase/seed/setup.json") as Json;
  const { $comment: _ignored, ...rest } = fixed;
  return [
    ...Object.entries(rest),
    ["hosts", defaults.hosts],
    ["health_paths", defaults.health_paths],
    ["vendors", defaults.vendors],
    ["vercel", defaults.vercel],
    ["chatwoot", defaults.chatwoot],
    ["test_identities", defaults.test_identities],
    ["supabase", defaults.supabase],
    ["setup", setup],
  ];
}

function sql(): string {
  const lines = [
    "-- 0007 one.settings seed. GENERATED by scripts/db/gen-seed.ts from config/defaults.json, config/settings.json and",
    "-- supabase/seed/setup.json; do not edit by hand (CI fails if this file is stale). one.settings_put with actor 'seed'",
    "-- never overwrites a value a person changed in the Settings page (spec §16.8).",
    "",
  ];
  for (const [key, value] of settings()) {
    const json = JSON.stringify(value);
    if (json.includes("$seed$")) throw new Error(`settings ${key} contains the dollar-quote tag`);
    lines.push(`select one.settings_put('${key}', $seed$${json}$seed$::jsonb, 'seed', 'seed: generated config');`);
  }
  lines.push("");
  return lines.join("\n");
}

const output = sql();
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== output) {
    console.error("0007_seed_settings.sql is stale: run node scripts/db/gen-seed.ts");
    process.exit(1);
  }
  console.log("0007_seed_settings.sql is current");
} else {
  writeFileSync(target, output);
  console.log(`wrote ${target.pathname}`);
}
