// Builds migration 0015 (the synthetic test catalogue) and docs/TESTS.md from config/tests.json (spec §10).
//   node scripts/db/gen-tests.ts            write both files
//   node scripts/db/gen-tests.ts --check    exit 1 if either file is stale (CI and the unit test)
// Each test's needs must be Setup items (config/setup-items.json), its schedule a cron the app's runner can read, and its
// steps unique keys with timeouts that fit inside the run's. The schedule comes from config/settings.json tests.schedules.
import { readFileSync, writeFileSync } from "node:fs";
import { parseCron } from "../../web/lib/tests/cron.ts";

export type TestStep = { key: string; title: string; timeout_s: number };
export type TestEntry = {
  id: string;
  app: string;
  title: string;
  seam: string;
  description: string;
  severity: "P1" | "P2" | "P3";
  timeout_s: number;
  needs: string[];
  steps: TestStep[];
  safety: string;
  purge: string;
  disabled?: string;
};

const root = new URL("../../", import.meta.url);
const read = (p: string) => readFileSync(new URL(p, root), "utf8");
const APPS = ["witty", "b2b", "b2c", "web", "influencer", "one"];

function fail(msg: string): never {
  throw new Error(`gen-tests: ${msg}`);
}

export function validate(tests: TestEntry[], setupIds: Set<string>, schedules: Record<string, string>): void {
  const ids = new Set<string>();
  for (const t of tests) {
    if (!/^T-[A-Z0-9-]+$/.test(t.id)) fail(`${t.id}: bad id`);
    if (ids.has(t.id)) fail(`${t.id}: duplicate`);
    ids.add(t.id);
    if (!APPS.includes(t.app)) fail(`${t.id}: unknown app ${t.app}`);
    if (!["P1", "P2", "P3"].includes(t.severity)) fail(`${t.id}: bad severity`);
    for (const k of ["title", "seam", "description", "safety", "purge"] as const) if (!t[k]?.trim()) fail(`${t.id}: no ${k}`);
    for (const n of t.needs) if (!setupIds.has(n)) fail(`${t.id}: needs ${n}, which is not a Setup item`);
    const schedule = schedules[t.id] ?? fail(`${t.id}: no schedule in config/settings.json tests.schedules`);
    try {
      parseCron(schedule);
    } catch (e) {
      fail(`${t.id}: schedule ${schedule}: ${e instanceof Error ? e.message : String(e)}`);
    }
    if (t.steps.length === 0) fail(`${t.id}: no steps`);
    const keys = new Set<string>();
    for (const s of t.steps) {
      if (!/^[a-z][a-z0-9_]{0,30}$/.test(s.key) || keys.has(s.key)) fail(`${t.id}: bad or repeated step key ${s.key}`);
      keys.add(s.key);
      if (!Number.isInteger(s.timeout_s) || s.timeout_s < 1 || s.timeout_s > t.timeout_s) fail(`${t.id}.${s.key}: timeout out of range`);
    }
    if (!Number.isInteger(t.timeout_s) || t.timeout_s < 60 || t.timeout_s > 6 * 3600) fail(`${t.id}: timeout_s out of range`);
    if (t.disabled !== undefined && !/^(blocked|builder):[a-z0-9_.:-]+$/.test(t.disabled)) fail(`${t.id}: bad disabled reason`);
  }
  for (const id of Object.keys(schedules)) if (!ids.has(id)) fail(`schedule for unknown test ${id}`);
}

const lit = (s: string) => `'${s.replaceAll("'", "''")}'`;

export function render(tests: TestEntry[], schedules: Record<string, string>): { sql: string; md: string } {
  const sql = [
    "-- 0015 the synthetic test catalogue (spec §10). GENERATED by scripts/db/gen-tests.ts from config/tests.json and the",
    "-- schedules in config/settings.json; do not edit by hand. Each test and its check are seeded off; one.tests_sync_setup()",
    "-- then switches on every test whose Setup items are all validated.",
    "",
    ...tests.map((t) => {
      const { safety: _s, purge: _p, ...rest } = t;
      const body = JSON.stringify({ ...rest, schedule: schedules[t.id] }, null, 2);
      return `select one.seed_test(${lit(body)}::jsonb);\n`;
    }),
    "select one.tests_sync_setup();",
    "",
  ].join("\n");
  const md = [
    "# Synthetic tests",
    "",
    "Generated by `scripts/db/gen-tests.ts` from `config/tests.json` (spec §10). Each test is a journey through one seam on",
    "the test identities only; every row it creates is `is_test` and is purged after `tests.purge_after_days` through the",
    "app's own delete path. A test runs only when every Setup item it needs is validated; until then it shows as not",
    "configured. Schedules are cron, UTC, editable on the Tests page.",
    "",
    "| ID | App | Seam | Severity | Schedule | Needs |",
    "| --- | --- | --- | --- | --- | --- |",
    ...tests.map((t) => `| ${t.id} | ${t.app} | ${t.seam} | ${t.severity} | \`${schedules[t.id]}\` | ${t.needs.join(", ") || "—"} |`),
    "",
    ...tests.flatMap((t) => [
      `## ${t.id}: ${t.title}`,
      "",
      t.description,
      "",
      `Run limit ${t.timeout_s} s.${t.disabled ? ` Off: \`${t.disabled}\`.` : ""}`,
      "",
      "| Step | Within |",
      "| --- | --- |",
      ...t.steps.map((s) => `| ${s.title} | ${s.timeout_s} s |`),
      "",
      `**Safety.** ${t.safety}`,
      "",
      `**Purge.** ${t.purge}`,
      "",
    ]),
  ].join("\n");
  return { sql, md };
}

export function build(): { sql: string; md: string } {
  const tests = JSON.parse(read("config/tests.json")).tests as TestEntry[];
  const catalog = JSON.parse(read("config/setup-items.json")) as { items: Array<{ id: string }> };
  const settings = JSON.parse(read("config/settings.json")) as { tests: { schedules: Record<string, string> } };
  validate(tests, new Set(catalog.items.map((i) => i.id)), settings.tests.schedules);
  return render(tests, settings.tests.schedules);
}

if (import.meta.main) {
  const { sql, md } = build();
  const targets: Array<[string, string]> = [
    ["supabase/migrations/0015_seed_tests.sql", sql],
    ["docs/TESTS.md", md],
  ];
  if (process.argv.includes("--check")) {
    const stale = targets.filter(([p, text]) => {
      try {
        return read(p) !== text;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(`stale: ${stale.map(([p]) => p).join(", ")}; run node scripts/db/gen-tests.ts`);
      process.exit(1);
    }
    console.log("tests current");
  } else {
    for (const [p, text] of targets) writeFileSync(new URL(p, root), text);
    console.log("wrote 0015_seed_tests.sql and docs/TESTS.md");
  }
}
