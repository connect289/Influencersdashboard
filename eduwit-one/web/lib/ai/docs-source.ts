import { createHash } from "node:crypto";

// Builds lib/ai/docs.generated.ts from the hand-over documents in docs/ (RUNBOOK.md, RUNBOOK-database.md,
// WALKTHROUGH.md), one entry per "## " section, so Ask can answer "how do I…" questions from the runbook itself (the
// runbook tool, D-083) and the Operate pages can quote it. The app ships the generated module; a unit test fails while
// it is stale, so the AI never reads an older runbook than the one in the repository.

export const DOC_FILES = ["RUNBOOK", "RUNBOOK-database", "WALKTHROUGH"] as const;
export type DocFile = (typeof DOC_FILES)[number];
export type DocSection = { file: DocFile; title: string; text: string };

/** Splits a markdown document at its "## " headings; the text before the first heading is the "About" section. */
export function sections(file: DocFile, markdown: string): DocSection[] {
  const out: DocSection[] = [];
  let title = "About";
  let lines: string[] = [];
  const flush = () => {
    const text = lines.join("\n").trim();
    if (text) out.push({ file, title, text });
  };
  for (const line of markdown.split("\n")) {
    const m = /^## (.+)$/.exec(line);
    if (m) {
      flush();
      title = (m[1] ?? "").trim();
      lines = [];
    } else if (!/^# /.test(line)) {
      lines.push(line);
    }
  }
  flush();
  return out;
}

export function docsModule(read: (file: DocFile) => string): string {
  const all = DOC_FILES.flatMap((f) => sections(f, read(f)));
  const version = createHash("sha256")
    .update(all.map((s) => `${s.file}#${s.title}\n${s.text}`).join("\n\n"))
    .digest("hex")
    .slice(0, 10);
  return [
    "// Generated by scripts/gen-docs.ts from docs/RUNBOOK.md, docs/RUNBOOK-database.md and docs/WALKTHROUGH.md. Do not",
    "// edit: edit the documents and run node scripts/gen-docs.ts (a unit test fails while this file is stale).",
    "",
    'import type { DocSection } from "./docs-source.ts";',
    "",
    `export const DOCS_VERSION = ${JSON.stringify(version)};`,
    `export const DOCS: DocSection[] = ${JSON.stringify(all, null, 2)};`,
    "",
  ].join("\n");
}

const STOP = new Set([
  "the",
  "and",
  "for",
  "how",
  "what",
  "does",
  "can",
  "with",
  "from",
  "that",
  "this",
  "into",
  "out",
]);
/** A crude stem, so "rotating" finds "rotate" and "keys" finds "key". */
const stem = (w: string) => (w.length > 4 ? w.replace(/(ing|ed|es|s|e)$/, "") : w);

/**
 * The sections whose title or text carry the words of the query, best first (a word in the title counts three times,
 * a word in the text once per occurrence up to five); an empty query lists them all. Nothing matches: an empty list.
 */
export function findSections(docs: DocSection[], query: string, limit = 3): DocSection[] {
  const words = [
    ...new Set(
      query
        .toLowerCase()
        .split(/[^a-z0-9_:-]+/)
        .filter((w) => w.length > 2 && !STOP.has(w))
        .map(stem),
    ),
  ];
  if (words.length === 0) return docs.slice(0, limit);
  const count = (hay: string, w: string) => Math.min(5, hay.split(w).length - 1);
  const scored = docs
    .map((d) => {
      const title = d.title.toLowerCase();
      const text = d.text.toLowerCase();
      const score = words.reduce((n, w) => n + (title.includes(w) ? 3 : 0) + count(text, w), 0);
      return { d, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((x) => x.d);
}
