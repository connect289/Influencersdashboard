import { createHash } from "node:crypto";

// Builds lib/ai/prompts.generated.ts from the prompt files in lib/ai/prompts (spec §11: prompts as markdown, each call
// stamped with its prompt_version). A version is the task kind and the first 10 hex digits of a sha256 over the shared
// rules and the kind's prompt, so editing either gives every call a new version. Used by scripts/gen-prompts.ts and by
// the unit test that fails when the generated module is stale.

export const PROMPT_NAMES = [
  "classify",
  "triage",
  "explain",
  "propose_fix",
  "propose_feature",
  "test_author",
  "brief",
  "ask",
  "chat",
] as const;

export function promptModule(read: (name: string) => string): string {
  const system = read("system").trim();
  const entries = PROMPT_NAMES.map((name) => {
    const text = read(name).trim();
    const version = `${name}@${createHash("sha256").update(`${system}\n\n${text}`).digest("hex").slice(0, 10)}`;
    return `  ${name}: { version: ${JSON.stringify(version)}, text: ${JSON.stringify(text)} },`;
  });
  return [
    "// Generated by scripts/gen-prompts.ts from lib/ai/prompts/*.md. Do not edit: edit the markdown and run",
    "// node scripts/gen-prompts.ts (a unit test fails while this file is stale).",
    "",
    `export const SYSTEM_PROMPT = ${JSON.stringify(system)};`,
    "",
    "export const PROMPTS = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}
