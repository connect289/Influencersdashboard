function channel(c: number): number {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const n = Number.parseInt(hex.slice(1), 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

export function tokensCss(): string {
  const block = (t: Theme) =>
    Object.entries(t)
      .map(([k, v]) => `  --${k}: ${v};`)
      .join("\n");
  return [
    "/* GENERATED by scripts/gen-tokens.ts from lib/brand/tokens.ts; do not edit. */",
    `:root {\n${block(themes.light)}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${block(themes.dark).replace(/^/gm, "  ")}\n    color-scheme: dark;\n  }\n}`,
    `:root[data-theme="dark"] {\n${block(themes.dark)}\n  color-scheme: dark;\n}`,
    "",
  ].join("\n\n");
}
