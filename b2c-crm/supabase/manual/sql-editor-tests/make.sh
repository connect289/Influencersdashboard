#!/usr/bin/env bash
# Rebuilds the SQL-editor copies of the test suites: the same checks, but the run always ends with an error carrying
# "TESTRESULT pass=N fail=M <failures>", because the SQL editor shows only the last statement. Raising also guarantees
# the rollback: nothing a suite writes is ever kept. Run from b2c-crm/supabase: bash manual/sql-editor-tests/make.sh
set -euo pipefail
cd "$(dirname "$0")/../.."
for f in tests/test_*.sql; do
  grep -q "LOCAL COPY ONLY" "$f" && continue   # catalogue and partner fixtures: local copy only
  out="manual/sql-editor-tests/$(basename "$f")"
  python3 - "$f" "$out" <<'PY'
import sys
src, out = sys.argv[1], sys.argv[2]
s = open(src).read().rstrip()
tail = "select n, name, ok, case when ok then null else detail end as detail from r order by n;\nrollback;"
assert s.endswith(tail), src
s = s[: -len(tail)] + """do $z$
declare f text;
begin
  select string_agg(n || ' ' || name || ': ' || coalesce(detail, ''), ' | ' order by n) into f from r where not ok;
  raise exception 'TESTRESULT pass=% fail=% %', (select count(*) from r where ok), (select count(*) from r where not ok), coalesce(f, '');
end $z$;
"""
open(out, "w").write("-- Generated by make.sh from " + src + " for the Supabase SQL editor. Expected: an error reading TESTRESULT ... fail=0.\n" + s)
PY
done
echo done
