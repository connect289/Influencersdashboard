#!/usr/bin/env node
// Generates supabase/seed.sql (local dev only) from supabase/seed/catalog_sample.json: the real catalogue rows exported
// read-only from production (no personal data). The fee-check trigger is disabled while loading so rows are exactly as
// production holds them (the loader already ran it there).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const data = JSON.parse(readFileSync(path.join(root, "supabase/seed/catalog_sample.json"), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(lit).join(",")}]::text[]`;
  if (typeof v === "object") return `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`;
  return `'${String(v).replaceAll("'", "''")}'`;
};
function inserts(table, rows, override = {}) {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const out = [`insert into ${table} (${cols.map((c) => `"${c}"`).join(", ")}) values`];
  out.push(rows.map((r) => `  (${cols.map((c) => (override[c] ? override[c](r[c]) : lit(r[c]))).join(", ")})`).join(",\n") + ";");
  return out.join("\n");
}

const sql = [
  "-- Local development seed (generated by scripts/db/make-seed.mjs). Real catalogue rows exported read-only from production",
  `-- on ${data._meta?.taken_at ?? "unknown date"}. Never run against production.`,
  "alter table public.catalog_programs disable trigger user;",
  inserts("public.catalog_universities", data.catalog_universities),
  inserts("public.catalog_programs", data.catalog_programs, { flags: (v) => `array[${(v ?? []).map(lit).join(",")}]::text[]` }),
  inserts("public.catalog_synonyms", data.catalog_synonyms),
  "alter table public.catalog_programs enable trigger user;",
  "select setval(pg_get_serial_sequence('public.catalog_universities','id'), (select max(id) from public.catalog_universities));",
  "select setval(pg_get_serial_sequence('public.catalog_programs','id'), (select max(id) from public.catalog_programs));",
  "insert into public.w2_meta (key, value) values ('catalog_version', '6'::jsonb) on conflict do nothing;",
  "-- Website: map the catalogue and build the search read model (production does this via web_catalog_poll).",
  "select public.web_refresh_read_model();",
  "-- e2e fixture: one admin-managed redirect (content.spec.ts).",
  "insert into public.web_redirects (from_path, to_path, code, source) values ('/old-mba-page', '/programmes/online-mba', 301, 'admin') on conflict do nothing;",
  "",
].join("\n\n");
writeFileSync(path.join(root, "supabase/seed.sql"), sql);
console.info(`wrote supabase/seed.sql (${sql.length} bytes)`);
