#!/usr/bin/env node
// Turns the crawl of the current site (content/legacy, from scripts/crawl-legacy-site.mjs) into a reviewable SQL file:
//  - the six legal pages, verbatim, as content blocks (status 'migrated')
//  - testimonial candidates (unpublished, consent unconfirmed — the owner confirms each one in the admin)
// Usage: node scripts/import-legacy.mjs [legacyDir] [outFile]   then review and apply the SQL (dev first).
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { LEGAL_SLUGS, lit, toContentBlocks } from "./lib/legacy-blocks.mjs";

const dir = path.resolve(process.argv[2] ?? path.join(import.meta.dirname, "../../content/legacy"));
const out = path.resolve(process.argv[3] ?? path.join(import.meta.dirname, "../../supabase/seed-legacy.sql"));
const pagesDir = path.join(dir, "pages");
if (!existsSync(pagesDir)) {
  console.error(`No crawl output at ${pagesDir}. Run scripts/crawl-legacy-site.mjs first (needs eduwit.in allowed — S-01).`);
  process.exit(1);
}
const sql = ["-- Generated by scripts/import-legacy.mjs from the crawl of the current site. Review before applying.", "begin;"];
for (const slug of LEGAL_SLUGS) {
  const file = path.join(pagesDir, `legal_${slug.replace(/-/g, "_")}.json`);
  if (!existsSync(file)) {
    sql.push(`-- missing: /legal/${slug} (not found in the crawl)`);
    continue;
  }
  const page = JSON.parse(readFileSync(file, "utf8"));
  const blocks = toContentBlocks(page.blocks ?? []);
  sql.push(`update public.web_legal_pages set body = ${lit(JSON.stringify(blocks))}::jsonb, status = 'migrated', migrated_at = now(), source_url = ${lit(page.url)}, updated_at = now() where slug = ${lit(slug)};`);
}
// Testimonial candidates: blocks inside a section whose id/class mentions testimonials.
for (const f of readdirSync(pagesDir).filter((x) => x.endsWith(".json"))) {
  const page = JSON.parse(readFileSync(path.join(pagesDir, f), "utf8"));
  for (const b of page.blocks ?? []) {
    if (/testimonial|review|stories/i.test(b.section ?? "") && b.tag === "p" && b.text.length > 40) {
      sql.push(`insert into public.web_testimonials (name, quote, source, consent_confirmed, published) values ('(name from the current site)', ${lit(b.text)}, 'legacy', false, false);`);
    }
  }
}
sql.push("commit;", "");
writeFileSync(out, sql.join("\n"));
console.info(`wrote ${out}`);
