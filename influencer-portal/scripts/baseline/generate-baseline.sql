-- Generates the exact DDL of the production objects the Influencer Portal reads, from the system catalog.
-- READ-ONLY: only SELECTs on pg_catalog. Run against production with any read-only role, e.g.
--   psql "$READONLY_DATABASE_URL" -At -f scripts/baseline/generate-baseline.sql > /tmp/exact.sql
-- The output becomes the "exact" part of supabase/migrations/00000000000000_shared_baseline.sql.
-- Objects from other products that the portal only reads through contract views are not generated here: the baseline
-- file defines shape-compatible stubs for them by hand (see the baseline's header).
with
tbls(rel, ord) as (values
  ('public.catalog_universities'::regclass, 1), ('public.catalog_programs'::regclass, 2), ('public.catalog_synonyms'::regclass, 3),
  ('public.student_leads'::regclass, 4), ('public.touchpoints'::regclass, 5), ('public.enrollments'::regclass, 6),
  ('public.w2_sources'::regclass, 7), ('public.w2_trusted'::regclass, 8), ('public.w2_clicks'::regclass, 9),
  ('public.w2_access_codes'::regclass, 10), ('public.w2_conversations'::regclass, 11)),
fns(name, ord) as (values
  ('crm_norm_phone', 1), ('w2_is_test', 2), ('crm_find_lead', 3), ('w2_crm_owned', 4), ('student_leads_touch', 5),
  ('lead_intake', 6), ('w2_issue_code', 7), ('w2_redeem_code', 8)),
seqs as (
  select distinct 100 as ord, format('create sequence if not exists %s;', s.seqrelid::regclass) as ddl
    from pg_sequence s join pg_depend d on d.objid = s.seqrelid and d.deptype in ('a', 'i')
    join tbls t on t.rel = d.refobjid),
cols as (
  select 200 + t.ord as ord,
         format(E'create table if not exists %s (\n%s\n);', t.rel,
           string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
             case a.attidentity when 'd' then ' generated by default as identity' when 'a' then ' generated always as identity' else '' end,
             case when ad.adbin is not null and a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                  when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
             case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)) as ddl
    from tbls t join pg_attribute a on a.attrelid = t.rel and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
   group by t.rel, t.ord),
owned as (
  select 300 as ord, format('alter sequence %s owned by %s.%I;', s.seqrelid::regclass, d.refobjid::regclass, a.attname) as ddl
    from pg_sequence s join pg_depend d on d.objid = s.seqrelid and d.deptype = 'a'
    join tbls t on t.rel = d.refobjid
    join pg_attribute a on a.attrelid = d.refobjid and a.attnum = d.refobjsubid),
cons as (
  select 400 + t.ord as ord, format('alter table %s add constraint %I %s;', t.rel, c.conname, pg_get_constraintdef(c.oid)) as ddl
    from tbls t join pg_constraint c on c.conrelid = t.rel
   where c.contype in ('p', 'u', 'c')
      or (c.contype = 'f' and c.confrelid in (select rel from tbls))),
idx as (
  select 500 + t.ord as ord, regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';' as ddl
    from tbls t join pg_index i on i.indrelid = t.rel
   where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)),
func as (
  select 600 + f.ord as ord, pg_get_functiondef(p.oid) || ';' as ddl
    from fns f join pg_proc p on p.proname = f.name and p.pronamespace = 'public'::regnamespace),
trg as (
  select 700 as ord, pg_get_triggerdef(tg.oid) || ';' as ddl
    from pg_trigger tg where tg.tgrelid = 'public.student_leads'::regclass and tg.tgname = 'student_leads_touch_trg'),
rls as (
  select 800 + t.ord as ord, format('alter table %s enable row level security;', t.rel) as ddl
    from tbls t join pg_class c on c.oid = t.rel where c.relrowsecurity)
select ddl from (
  select * from seqs union all select * from cols union all select * from owned union all select * from cons
  union all select * from idx union all select * from func union all select * from trg union all select * from rls) x
order by ord, ddl;
