-- Part 1 of the shared baseline (hand-written, LOCAL ONLY).
-- Shape-compatible stubs of objects owned by other products that the portal reads (or that the exact part needs to
-- compile). Column names and types match production as read on 16 Oct 2026; bodies and data do not.

create extension if not exists pg_trgm with schema extensions;
create extension if not exists pgcrypto with schema extensions;

-- ---------- B2B CRM (schema b2b): only the columns the portal or the exact functions reference ----------
create schema if not exists b2b;

create table if not exists b2b.partners (
  id bigint generated by default as identity primary key,
  name text not null default 'Partner',
  status text not null default 'active'
);

create table if not exists b2b.partner_programmes (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references b2b.partners (id),
  programme_id bigint not null,
  fees jsonb not null default '{}'::jsonb,
  intake text,
  season_to date,
  valid_from date not null default current_date,
  valid_to date,
  active boolean not null default true
);

create table if not exists b2b.allocations (
  id bigint generated by default as identity primary key,
  lead_id bigint not null,
  destination_type text,
  status text not null default 'queued'
);

-- Commission per enrollment (read by inf.commission_receipts_sync, INTEGRATION_CONTRACTS.md §3).
create table if not exists b2b.earnings (
  id bigint generated by default as identity primary key,
  enrollment_id bigint, allocation_id bigint, partner_id bigint, lead_id bigint,
  period text not null default to_char(now(), 'YYYY-MM'),
  kind text not null default 'commission', status text not null default 'expected',
  rate_id bigint, rate_snapshot jsonb, fee_base_inr numeric, pct numeric, tier_provisional boolean not null default false,
  net_inr numeric not null default 0, gst_rate numeric, gst_inr numeric not null default 0, gross_inr numeric not null default 0,
  reverses_id bigint, adjusts_id bigint, invoice_id bigint, note text, realised_at timestamptz,
  created_at timestamptz not null default now(), created_by text
);

create table if not exists b2b.invoices (
  id bigint generated by default as identity primary key,
  partner_id bigint, through_period text, status text not null default 'draft', fy text, seq integer, number text,
  issue_date date, due_date date, supplier jsonb, recipient jsonb, sac_code text, place_of_supply text, tax_type text,
  gst_rate numeric, taxable_inr numeric, cgst_inr numeric, sgst_inr numeric, igst_inr numeric, total_inr numeric,
  received_inr numeric, tds_inr numeric, reminded_bucket text, notes text, approved_at timestamptz, sent_at timestamptz,
  paid_at timestamptz, cancelled_at timestamptz, cancel_reason text, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(), created_by text
);

-- ---------- B2C CRM: contract views (tables here, views in production; the portal only selects) ----------
create schema if not exists b2c;

create table if not exists b2c.enrollments (
  id bigint generated by default as identity primary key,
  lead_id bigint not null, application_id bigint, counsellor_id uuid, university text, programme text, fee numeric,
  fee_paid numeric, enrolled_on date, proof_path text, status text not null default 'reported', note text,
  verified_by uuid, verified_at timestamptz, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(), university_id bigint, programme_id bigint, fee_first_year numeric,
  refunded_on date, refund_reason text
);

create table if not exists public.b2c_lead_status_v (
  view_version integer not null default 1, lead_id bigint primary key, lane text, status text, stage text, sub_stage text,
  canonical_stage text, stage_changed_at timestamptz, counsellor text, counsellor_email text, assigned_at timestamptz,
  pool_reason text, journey text, reengaged_at timestamptz, reengage_trigger text, closed_at timestamptz,
  closed_reason text, routing_requested_at timestamptz, is_test boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.b2c_enrollment_money_v (
  view_version integer not null default 1, lead_id bigint not null, enrollment_id bigint primary key, enrolled_on date,
  university text, programme text, enrollment_status text, university_commission_gross numeric,
  university_commission_gst numeric, university_commission_net numeric, university_commission_status text,
  invoice text, counsellor_commission_total numeric
);

-- In production both are granted to service_role only.
revoke all on public.b2c_lead_status_v, public.b2c_enrollment_money_v from anon, authenticated;

-- ---------- Old CRM and legacy influencer objects that shape access to student_leads (exact copies) ----------
create table if not exists public.crm_users (
  id uuid primary key,
  email text not null,
  full_name text,
  role text not null default 'viewer',
  is_active boolean not null default false
);
alter table public.crm_users enable row level security;

create table if not exists public.influencers (
  id uuid primary key default gen_random_uuid(),
  auth_uid uuid not null,
  referral_code text not null,
  email text,
  name text,
  created_at timestamptz not null default now(),
  status text not null default 'active'
);
alter table public.influencers enable row level security;
