// Generates supabase/tests/020_ledger_status_matrix.sql from lib/ledger/lifecycle.ts, so the database's copy of the
// entry lifecycle (inf.ledger_status_of, inf.ledger_can_transition) can't drift from the TypeScript one. Every
// combination on a grid of entry facts and every pair of statuses is checked. Written by npm run gen:sql; a unit test
// fails if it is stale.
import { canTransition, ENTRY_STATUSES, statusOf, STATUS_TODAY, type EntryState } from "@/lib/ledger/lifecycle";

export function ledgerStates(): EntryState[] {
  const out: EntryState[] = [];
  for (const amount of [0, 1000])
    for (const confirmed of [0, 400, 1000])
      for (const paid of [0, 400, 1000])
        for (const open of [false, true])
          for (const held of [false, true])
            for (const reversed of [false, true])
              for (const isReversal of [false, true])
                for (const due of ["2026-11-01", STATUS_TODAY, "2026-12-01"]) {
                  if (confirmed > amount || (isReversal && (paid > confirmed || reversed))) continue;
                  out.push({
                    amount_paise: amount,
                    confirmed_paise: confirmed,
                    paid_paise: paid,
                    in_open_batch: open,
                    held,
                    reversed,
                    is_reversal: isReversal,
                    due_on: due,
                  });
                }
  return out;
}

export function ledgerMatrixSql(): string {
  const states = ledgerStates().map(
    (s) =>
      `(${String(s.amount_paise)},${String(s.confirmed_paise)},${String(s.paid_paise)},${String(s.in_open_batch)},${String(s.held)},` +
      `${String(s.reversed)},${String(s.is_reversal)},'${s.due_on}','${statusOf(s, STATUS_TODAY)}')`,
  );
  const pairs = ENTRY_STATUSES.flatMap((a) =>
    ENTRY_STATUSES.map((b) => `('${a}','${b}',${String(canTransition(a, b))})`),
  );
  return `-- GENERATED by npm run gen:sql from lib/ledger/lifecycle.ts. Do not edit.
-- The database lifecycle (inf.ledger_status_of, inf.ledger_can_transition) matches the TypeScript one for every
-- combination of entry facts on the grid and every pair of statuses.
begin;
\\ir _helpers.psql
select plan(2);

create temporary table expected_status (amount bigint, confirmed bigint, paid bigint, open boolean, held boolean, reversed boolean,
                                        is_reversal boolean, due date, status text);
insert into expected_status values
${states.join(",\n")};
select is_empty($$ select * from expected_status
                    where inf.ledger_status_of(amount, confirmed, paid, open, held, reversed, is_reversal, due, '${STATUS_TODAY}') <> status $$,
                'every entry state derives the same status as lib/ledger/lifecycle.ts');

create temporary table expected_transitions (a text, b text, ok boolean);
insert into expected_transitions values
${pairs.join(",\n")};
select is_empty($$ select * from expected_transitions where inf.ledger_can_transition(a, b) <> ok $$,
                'the allowed status changes match lib/ledger/lifecycle.ts');

select * from finish();
rollback;
`;
}
