// Generates supabase/tests/017_workflow_matrix.sql from lib/content/workflow.ts, so the database's copy of the
// workflow (inf.deliverable_next, inf.deliverable_pending) can't drift from the one the UI uses. Every status ×
// action × stage-switch combination is checked: the file lists the allowed moves and pending stages, and the test
// asserts the database answers exactly that set (nothing missing, nothing extra). Written by npm run gen:sql; a unit
// test fails if it is stale.
import { ACTIONS, DELIVERABLE_STATUSES, move, pendingStage, STAGES, type StageToggles } from "@/lib/content/workflow";

const combos = (): { bits: number; t: StageToggles }[] =>
  Array.from({ length: 1 << STAGES.length }, (_, bits) => ({
    bits,
    t: Object.fromEntries(STAGES.map((s, i) => [s, (bits & (1 << i)) !== 0])) as StageToggles,
  }));

export function workflowMatrixSql(): string {
  const moves: string[] = [];
  const pending: string[] = [];
  for (const { bits, t } of combos()) {
    for (const s of DELIVERABLE_STATUSES) {
      for (const a of ACTIONS) {
        const r = move(s, a, t);
        if (r.ok) moves.push(`('${s}','${a}',${String(bits)},'${r.to}')`);
      }
      const p = pendingStage(s, t);
      if (p) pending.push(`('${s}',${String(bits)},'${p}')`);
    }
  }
  const toggles = STAGES.map((s, i) => `'${s}', (b & ${String(1 << i)}) <> 0`).join(", ");
  return `-- GENERATED by npm run gen:sql from lib/content/workflow.ts. Do not edit.
-- The database workflow (inf.deliverable_next, inf.deliverable_pending) matches the TypeScript workflow for every
-- status, action and combination of stage switches.
begin;
\\ir _helpers.psql
select plan(4);

create temporary table combos as select b, jsonb_build_object(${toggles}) as t from generate_series(0, ${String((1 << STAGES.length) - 1)}) b;
create temporary table statuses (s text);
insert into statuses values ${DELIVERABLE_STATUSES.map((s) => `('${s}')`).join(", ")};
create temporary table actions (a text);
insert into actions values ${ACTIONS.map((a) => `('${a}')`).join(", ")};
create temporary table expected_moves (s text, a text, b int, dest text);
insert into expected_moves values
${moves.join(",\n")};
create temporary table expected_pending (s text, b int, stage text);
insert into expected_pending values
${pending.join(",\n")};
create temporary table actual_moves as
  select st.s, ac.a, c.b, inf.deliverable_next(st.s, ac.a, c.t) as dest from statuses st, actions ac, combos c;
create temporary table actual_pending as select st.s, c.b, inf.deliverable_pending(st.s, c.t) as stage from statuses st, combos c;

select is_empty($$ select s, a, b, dest from expected_moves except select s, a, b, dest from actual_moves $$,
                'every move the TypeScript workflow allows, the database allows with the same result');
select is_empty($$ select s, a, b, dest from actual_moves where dest is not null except select s, a, b, dest from expected_moves $$,
                'the database allows no move the TypeScript workflow refuses');
select is_empty($$ select s, b, stage from expected_pending except select s, b, stage from actual_pending $$,
                'the pending stage matches wherever TypeScript has one');
select is_empty($$ select s, b, stage from actual_pending where stage is not null except select s, b, stage from expected_pending $$,
                'the database has no pending stage TypeScript lacks');

select * from finish();
rollback;
`;
}
