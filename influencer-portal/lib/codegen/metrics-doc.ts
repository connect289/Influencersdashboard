// Generates docs/METRICS.md from the metric registry (lib/analytics/metrics.ts) and the English labels and
// definitions in messages/en.json, so the document, the formulas and the UI tooltips cannot drift apart.
import messages from "@/messages/en.json";
import { METRIC_GROUPS, METRIC_IDS, METRICS, type MetricId } from "@/lib/analytics/metrics";

type Msg = { label: string; definition: string };
const metricMsgs = messages.analytics.metrics as Record<MetricId, Msg>;
const groupNames = messages.analytics.groups as Record<(typeof METRIC_GROUPS)[number], string>;

const UNIT: Record<string, string> = {
  count: "Count",
  money: "₹ (paise stored, rupees shown)",
  percent: "Percent",
  ratio: "Ratio (×)",
  date: "Date (IST)",
};
const BASIS: Record<string, string> = {
  period: "In the selected date range",
  now: "Now (ignores the date range)",
  all_time: "To date (ignores the date range)",
};
const POLARITY: Record<string, string> = {
  up_is_good: "Higher is better",
  down_is_good: "Lower is better",
  neutral: "Neither",
};

const cell = (s: string) => s.replace(/\|/g, "\\|");

export function metricsMarkdown(): string {
  const out: string[] = [
    "# Metrics",
    "",
    "<!-- Generated by `npm run gen:sql` from lib/analytics/metrics.ts and messages/en.json. Do not edit by hand. -->",
    "",
    "Every number on a dashboard is defined here (spec 12). The **label** and **definition** are what the dashboard",
    "shows in its tooltip; the **formula** and **source** say exactly how it is computed.",
    "",
    "Common rules:",
    "",
    "- Dates are Indian Standard Time calendar days. A range includes both its first and last day.",
    "- The comparison period has the same number of days and ends the day before the range starts.",
    "- Money is stored in whole paise and shown in rupees with Indian digit grouping. Spend is before TDS and GST.",
    "- A rate or average whose denominator is zero shows “—”, never 0.",
    "- Staff dashboards read summary views refreshed every 15 minutes (the time of the last refresh is shown). A",
    "  creator's own home dashboard reads live data.",
    "- Creators see only their own figures, never Eduwit's revenue, margin or other creators' numbers (except their",
    "  own leaderboard position when they opt in).",
    "",
  ];
  for (const g of METRIC_GROUPS) {
    const ids = METRIC_IDS.filter((id) => METRICS[id].group === g);
    if (!ids.length) continue;
    out.push(`## ${groupNames[g]}`, "");
    for (const id of ids) {
      const d = METRICS[id];
      const msg = metricMsgs[id];
      out.push(
        `### ${msg.label} (\`${id}\`)`,
        "",
        msg.definition,
        "",
        "| | |",
        "| --- | --- |",
        `| Formula | ${cell(d.formula)} |`,
        `| Unit | ${UNIT[d.unit] ?? d.unit} |`,
        `| Period | ${BASIS[d.basis] ?? d.basis} |`,
        `| Direction | ${POLARITY[d.polarity] ?? d.polarity} |`,
        `| Source | ${cell(d.source)} |`,
        "",
      );
    }
  }
  return out.join("\n");
}
